# Proof test
# ---------------------------------------------------------------------------

def prove_canonical(verbose=True):
    """Prove the canonical form correct on real data.

    1. Each generator in isolation preserves feasibility (Laderman-23 stays
       feasible) -- the symmetry group is tested, not asserted. This step
       already caught one wrong assumption (naive cyclic rotation).
    2. 20 random symmetries of Laderman-23 all give the IDENTICAL canonical form.
    3. naive-2x2 vs strassen-2x2 give DIFFERENT canonical forms (not everything
       collides).
    4. strassen-2x2 vs a randomly symmetrized strassen-2x2 give the SAME form
       (nontrivial positive control: genuinely equivalent, non-identical inputs).

    Returns a dict of evidence. Raises AssertionError on any failure.
    """
    from verify import check
    from composition import REGISTRY

    evidence = {}
    lad = REGISTRY["laderman-23"].factors()
    assert check(lad, 3)["feasible"]

    # 1. each generator preserves feasibility
    rng = random.Random(12345)
    n = 3
    s = list(range(n))
    rng.shuffle(s)
    t = list(range(n))
    rng.shuffle(t)
    generators = {
        "triple_permutation": permute_triples(lad, list(reversed(range(len(lad))))),
        "sign_flips": [sign_flip_triple(tr, (i % 3) + 1) for i, tr in enumerate(lad)],
        "index_permutation": [index_permute(tr, s, t) for tr in lad],
    }
    generators.update({
        f"factor_rearrangement_{i}": [rearrange_factors(tr, i) for tr in lad]
        for i in range(6)
    })
    for name, transformed in generators.items():
        res = check(transformed, 3)
        assert res["feasible"], f"generator {name} broke feasibility: {res['reason']}"
        evidence[f"generator_{name}_preserves_feasibility"] = True
    if verbose:
        print(f"  all {len(generators)} generator cases preserve feasibility on Laderman-23")

    # 2. random symmetries -> identical canonical form
    c0 = canonical_form(lad, 3)
    for trial in range(20):
        rt = random.Random(9000 + trial)
        sym = apply_symmetry(lad, 3, rt)
        assert check(sym, 3)["feasible"], f"trial {trial}: symmetry broke feasibility"
        assert canonical_form(sym, 3) == c0, f"trial {trial}: canonical form changed!"
    evidence["laderman_20_random_symmetries_identical"] = True
    if verbose:
        print("  20 random symmetries of Laderman-23 -> identical canonical form")

    # 3. genuinely different decompositions differ
    naive2 = REGISTRY["naive-2x2"].factors()
    strassen2 = REGISTRY["strassen-2x2"].factors()
    assert canonical_form(naive2, 2) != canonical_form(strassen2, 2)
    evidence["naive_vs_strassen_differ"] = True
    if verbose:
        print("  naive-2x2 vs strassen-2x2 -> different canonical forms")

    # 4. nontrivial equivalence detected
    sym_s = apply_symmetry(strassen2, 2, random.Random(777))
    assert canonical_form(sym_s, 2) == canonical_form(strassen2, 2)
    evidence["strassen_vs_symmetrized_strassen_same"] = True
    if verbose:
        print("  strassen-2x2 vs symmetrized strassen-2x2 -> same canonical form")

    evidence["canonical_key_triples"] = len(c0)
    return evidence


if __name__ == "__main__":
    ev = prove_canonical(verbose=True)
    print("CANONICAL-FORM PROOF PASSED:", ev)
